// Fixture dataset for the disconnected frontend.
//
// The Go backend is not deployed, so every screen would render its error state.
// These fixtures are typed against `lib/types.ts` — the same contract mirror the
// real client uses — so swapping back to a live API needs no page or component
// change. See docs/adr/0003-mock-data-layer.md for why this is a deliberate,
// flagged exception to AGENTS.md §6.6.
//
// Nothing here computes money: every `*_kobo` value is written as a literal, the
// way the backend would return it. Formatters stay display-only.
//
// Consistency rules (so an advertiser can add up the table):
// - Every campaign keeps `total_budget_kobo = spend_kobo + remaining_budget_kobo`.
// - `businessAnalytics` top-level impressions/clicks/spend/remaining are the
//   sums across CURRENT_BUSINESS_ID campaigns; `by_format` groups those same
//   rows by `ad_type`; `series` is the monthly split that sums to the totals.
// - Ranged reads (`?range=…`) scope impressions/clicks/spend to the returned
//   series — the mock mirrors a backend that scopes totals by range — while
//   remaining (a now-balance) and by_format stay all-time. The KPI tiles
//   therefore always agree with the chart on every range.
// - `developerAnalytics` mirrors that for CURRENT_DEVELOPER_ID earnings:
//   impressions/revenue are the earnings sums, `filled = impressions`,
//   `by_format` groups earnings, `series` sums to the totals.
// - Ledger credits match confirmed payments; debits sum to total spend, so
//   credits − debits = wallet remaining. Paid payouts match paid earnings.

